"""Measure real token counts so the offline estimator can be checked against them.

What: `make calibrate` -> writes tests/data/token_calibration.json: exact sample texts
      (our tool schemas, system prompt, seeded chat lines, a compact-JSON tool result)
      with the provider's real token count for each, plus the hidden overhead the
      provider adds whenever tools are offered.

Why:  The context budget is enforced with an offline estimate (evals run without a
      network), so the estimate must never be *below* the real count (BUG-7: chars/3.5
      undercounted by ~45%). Claude's tokenizer isn't published; Anthropic's
      `count_tokens` endpoint is the reference, and it's free (rate-limited only).

How:  - Each text's real cost is measured as the marginal count inside a user message
        (count with the text minus count without), so message framing cancels out.
        Tool schemas are measured as the `tools` parameter, net of the tool-use
        overhead, which is measured with a single tiny tool.
      - Only measures and records. The ratios in memory/tokens.py are updated by hand
        (with the model and date), and a test checks the estimate against this file.
      - Needs ERRAND_MODEL (an anthropic:* model) and ANTHROPIC_API_KEY in backend/.env.
"""

import asyncio
import json
import tempfile
from datetime import date
from pathlib import Path

from anthropic import Anthropic

from errand_agent.agent.orchestrator import orchestrator_tools
from errand_agent.agent.prompts import SYSTEM_PROMPT
from errand_agent.agent.toon import to_toon
from errand_agent.core.clock import SystemClock
from errand_agent.core.config import load_settings
from errand_agent.core.ids import RandomIdGen
from errand_agent.memory.seedgen import DEMO_USER_ID, OUTPUT
from errand_agent.mocks.scenario import Scenario
from errand_agent.mocks.world import MockWorld

FIXTURE = Path(__file__).resolve().parents[1] / "tests" / "data" / "token_calibration.json"
HI = [{"role": "user", "content": "hi"}]
TINY_TOOL = {"name": "noop", "description": "x", "input_schema": {"type": "object"}}


def main() -> None:
    settings = load_settings()
    provider, _, model = settings.model.partition(":")
    if provider != "anthropic" or settings.anthropic_api_key is None:
        raise SystemExit("calibration needs an anthropic:* ERRAND_MODEL and ANTHROPIC_API_KEY")
    client = Anthropic(api_key=settings.anthropic_api_key.get_secret_value())

    def count(messages: list[dict[str, str]] = HI, tools: list[dict] | None = None) -> int:
        extra = {"tools": tools} if tools else {}
        return client.messages.count_tokens(model=model, messages=messages, **extra).input_tokens

    base = count()

    def marginal(text: str) -> int:
        return count([{"role": "user", "content": "hi\n" + text}]) - base

    schemas = [
        {
            "name": t.tool_def.name,
            "description": t.tool_def.description or "",
            "input_schema": t.tool_def.parameters_json_schema,
        }
        for t in orchestrator_tools()
    ]
    with_tiny = count(tools=[TINY_TOOL])
    schemas_text = json.dumps(
        [
            {"name": s["name"], "description": s["description"], "parameters": s["input_schema"]}
            for s in schemas
        ]
    )  # the same serialization agent/budget.py estimates

    seed = json.loads(OUTPUT.read_text())
    chat = "\n".join(m["content"] for s in seed["sessions"][:3] for m in s["messages"])
    bookings = asyncio.run(_bookings_json())

    samples = [
        {
            "name": "tool_schemas",
            "kind": "json",
            "text": schemas_text,
            "real_tokens": count(tools=schemas) - with_tiny,
        },
        {
            "name": "system_prompt",
            "kind": "prose",
            "text": SYSTEM_PROMPT,
            "real_tokens": marginal(SYSTEM_PROMPT),
        },
        {"name": "seeded_chat", "kind": "prose", "text": chat, "real_tokens": marginal(chat)},
        {
            "name": "bookings_result",
            "kind": "json",
            "text": bookings,
            "real_tokens": marginal(bookings),
        },
        {  # the same bookings as TOON (experiment/toon): dense data, so counted as JSON
            "name": "bookings_toon",
            "kind": "json",
            "text": (toon := to_toon("bookings", json.loads(bookings))),
            "real_tokens": marginal(toon),
        },
    ]
    result = {
        "_comment": "Generated by scripts/calibrate_tokens.py (make calibrate). Do not edit.",
        "model": model,
        "measured_on": date.today().isoformat(),
        "tool_use_overhead": with_tiny - base,  # includes the tiny tool's own few tokens
        "samples": samples,
    }
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {FIXTURE} ({model})")
    print(f"tool-use overhead: {result['tool_use_overhead']}")
    for s in samples:
        print(
            f"{s['name']:16} {s['kind']:5} {len(s['text']):>6} chars"
            f" {s['real_tokens']:>6} tokens  {len(s['text']) / s['real_tokens']:.2f} chars/token"
        )


async def _bookings_json() -> str:
    """The demo user's booking history as compact JSON: a typical list-shaped result."""
    with tempfile.TemporaryDirectory() as tmp:
        world = MockWorld.open(
            Path(tmp) / "mock.db",
            clock=SystemClock(),
            ids=RandomIdGen(),
            scenario=Scenario(),
            user_id=DEMO_USER_ID,
        )
        bookings = await world.list_bookings(DEMO_USER_ID)
        world.close()
    return json.dumps([b.model_dump(mode="json") for b in bookings], separators=(",", ":"))


if __name__ == "__main__":
    main()
