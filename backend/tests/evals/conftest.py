"""Eval results: each scenario's expected / actual / pass-fail / notes, as a table.

Every eval test is marked `@pytest.mark.eval(scenario=..., category=..., expected=...)`
and fills in `report.actual` (and `report.notes`) as it runs. The results are collected
from pytest's own pass/fail, so the table can't disagree with the run. With
`--eval-table PATH` (`make evals`), the table is written there at the end; a plain
`make test` runs the same scenarios and writes nothing.
"""

import subprocess
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import pytest

RESULTS_KEY = pytest.StashKey[list["EvalRow"]]()  # the session's rows, in run order


@dataclass
class EvalRow:
    scenario: str
    category: str
    expected: str
    actual: str = ""
    notes: str = ""
    passed: bool = False


ROW_KEY = pytest.StashKey[EvalRow]()  # one test's row


@pytest.fixture
def report(request: pytest.FixtureRequest) -> EvalRow:
    marker = request.node.get_closest_marker("eval")
    assert marker is not None, "an eval needs @pytest.mark.eval(scenario=, category=, expected=)"
    row = EvalRow(**marker.kwargs)
    request.node.stash[ROW_KEY] = row
    return row


def pytest_configure(config: pytest.Config) -> None:
    config.stash[RESULTS_KEY] = []


@pytest.hookimpl(wrapper=True)
def pytest_runtest_makereport(item: pytest.Item, call: pytest.CallInfo[None]) -> Any:
    result = yield
    if call.when == "call" and ROW_KEY in item.stash:
        row = item.stash[ROW_KEY]
        row.passed = result.passed
        if result.failed and not row.actual:
            row.actual = "failed: " + _summary(str(call.excinfo.value) if call.excinfo else "")
        item.config.stash[RESULTS_KEY].append(row)
    return result


def pytest_sessionfinish(session: pytest.Session) -> None:
    path = session.config.getoption("--eval-table")
    rows = session.config.stash[RESULTS_KEY]
    if path and rows:
        Path(path).write_text(_table(rows))


def _table(rows: list[EvalRow]) -> str:
    passed = sum(r.passed for r in rows)
    lines = [
        "# Eval results",
        "",
        f"Generated by `make evals` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC at commit"
        f" `{_commit()}`: **{passed}/{len(rows)} passed**. Scenarios run offline against a"
        " scripted model, through the real handler, workflow and mock providers; every"
        " one also checks the global invariants (tests/evals/harness.py). Do not edit by"
        " hand.",
        "",
        "| # | Scenario | Category | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(rows, start=1):
        result = "pass" if r.passed else "**FAIL**"
        cells = [str(i), r.scenario, r.category, r.expected, r.actual, result, r.notes]
        safe = (c.replace("|", "\\|").replace("\n", " ") for c in cells)  # one table row
        lines.append("| " + " | ".join(safe) + " |")
    return "\n".join(lines) + "\n"


def _commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _summary(text: str) -> str:
    """The failure on one line (an invariant list spans several), at most 200 chars."""
    flat = " ".join(line.strip() for line in text.strip().splitlines())
    return flat[:200] if flat else "error"
